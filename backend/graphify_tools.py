import json
import subprocess
import sys
from pathlib import Path
from typing import List, Dict, Any, Optional

PROJECT_ROOT = Path(__file__).resolve().parent.parent
GRAPH_DIR = PROJECT_ROOT / "graphify-out"
GRAPH_PATH = GRAPH_DIR / "graph.json"
REPORT_PATH = GRAPH_DIR / "GRAPH_REPORT.md"
HTML_PATH = GRAPH_DIR / "graph.html"

def get_graph_summary() -> Dict[str, Any]:
    """
    Returns high-level graph statistics and architectural report generated by Graphify.
    """
    if not GRAPH_PATH.exists():
        return {
            "available": False,
            "nodes_count": 0,
            "edges_count": 0,
            "communities_count": 0,
            "god_nodes": [],
            "report_summary": "",
        }

    try:
        with open(GRAPH_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        nodes = data.get("nodes", [])
        links = data.get("links", [])

        # Parse God nodes (nodes with highest degree)
        degree_map: Dict[str, int] = {}
        for l in links:
            degree_map[l["source"]] = degree_map.get(l["source"], 0) + 1
            degree_map[l["target"]] = degree_map.get(l["target"], 0) + 1

        node_dict = {n["id"]: n for n in nodes}
        sorted_nodes = sorted(degree_map.items(), key=lambda x: x[1], reverse=True)
        god_nodes = [
            {"label": node_dict.get(nid, {}).get("label", nid), "edges": deg, "file": node_dict.get(nid, {}).get("source_file", "")}
            for nid, deg in sorted_nodes[:8]
        ]

        report_summary = ""
        if REPORT_PATH.exists():
            report_lines = REPORT_PATH.read_text(encoding="utf-8").splitlines()
            # Capture overview lines
            filtered = [l for l in report_lines if l.startswith("## ") or l.startswith("- ")][:15]
            report_summary = "\n".join(filtered)

        return {
            "available": True,
            "nodes_count": len(nodes),
            "edges_count": len(links),
            "communities_count": len(set(n.get("community", 0) for n in nodes)),
            "god_nodes": god_nodes,
            "report_summary": report_summary,
            "built_at": data.get("built_at_commit", "local"),
        }
    except Exception as e:
        return {
            "available": False,
            "error": str(e),
            "nodes_count": 0,
            "edges_count": 0,
            "communities_count": 0,
            "god_nodes": [],
            "report_summary": "",
        }

def get_graph_context_for_files(file_paths: List[str]) -> str:
    """
    Extracts Graphify AST relationships for the specified source files.
    Identifies function definitions, outgoing calls, incoming calls, and dependencies.
    """
    if not GRAPH_PATH.exists():
        return ""

    try:
        with open(GRAPH_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception:
        return ""

    nodes = {n["id"]: n for n in data.get("nodes", [])}
    links = data.get("links", [])

    norm_targets = [p.replace("\\", "/").lower() for p in file_paths]

    target_node_ids = set()
    file_to_nodes: Dict[str, List[Dict[str, Any]]] = {}

    for nid, node in nodes.items():
        src = (node.get("source_file") or "").replace("\\", "/").lower()
        for norm_t in norm_targets:
            if norm_t in src or src.endswith(norm_t) or norm_t.endswith(src):
                target_node_ids.add(nid)
                file_to_nodes.setdefault(node.get("source_file", norm_t), []).append(node)
                break

    if not target_node_ids:
        if REPORT_PATH.exists():
            try:
                report_text = REPORT_PATH.read_text(encoding="utf-8")
                lines = report_text.splitlines()
                summary_lines = [l for l in lines if l.startswith("## ") or l.startswith("- ") or l.startswith("1.") or l.startswith("2.")]
                return "\n".join(summary_lines[:20])
            except Exception:
                pass
        return ""

    lines = [
        "=== GRAPHIFY CODE GRAPH & CALL-FLOW RELATIONSHIPS ===",
        "Graphify AST Structural Analysis for active files:",
    ]

    for fpath, f_nodes in file_to_nodes.items():
        fn_labels = [n.get("label", "") for n in f_nodes if n.get("_callable") or "()" in n.get("label", "")]
        if fn_labels:
            lines.append(f"• File `{fpath}` defines: {', '.join(fn_labels[:10])}")

    outgoing_calls = []
    incoming_calls = []

    for l in links:
        rel = l.get("relation", "")
        src_id = l.get("source")
        tgt_id = l.get("target")

        if src_id in target_node_ids:
            s_name = nodes.get(src_id, {}).get("label", src_id)
            t_name = nodes.get(tgt_id, {}).get("label", tgt_id)
            loc = l.get("source_location") or ""
            loc_str = f" ({loc})" if loc else ""
            if rel in ("calls", "imports", "uses", "instantiates"):
                outgoing_calls.append(f"  - `{s_name}` {rel} `{t_name}`{loc_str}")

        if tgt_id in target_node_ids and src_id not in target_node_ids:
            s_name = nodes.get(src_id, {}).get("label", src_id)
            t_name = nodes.get(tgt_id, {}).get("label", tgt_id)
            if rel in ("calls", "uses"):
                incoming_calls.append(f"  - `{s_name}` {rel} `{t_name}` (external caller)")

    if outgoing_calls:
        lines.append("• Structural Dependencies & Outgoing Calls:")
        lines.extend(outgoing_calls[:12])

    if incoming_calls:
        lines.append("• Incoming Callers / Dependent Modules:")
        lines.extend(incoming_calls[:8])

    return "\n".join(lines)
